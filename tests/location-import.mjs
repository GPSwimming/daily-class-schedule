import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import vm from "node:vm";
import { catalog } from "./catalog-fixture.mjs";

const source = await readFile(new URL("../dist/location-import.js", import.meta.url), "utf8");
const context = { window: {} };
vm.runInNewContext(source, context);
const api = context.window.SwimLocationImport;

assert.equal(api.referenceRows.length, 0, "pool details are absent from public JavaScript");
api.setReferenceRows(catalog.locations);
assert.equal(api.referenceRows.length, catalog.locations.length, "authenticated catalog populates locations");
assert.equal(new Set(api.referenceRows.map(api.key)).size, catalog.locations.length, "pool and place pairs are unique");
const initial = api.plan(api.referenceRows, []);
assert.equal(initial.add, catalog.locations.length, "first import adds combinations");
const saved = api.referenceRows.map((row, index) => ({ id: `place-${index}`, ...row }));
const repeat = api.plan(api.referenceRows, saved);
assert.equal(repeat.same, catalog.locations.length, "repeat import changes nothing");
const edited = [{ ...api.referenceRows[0], cleaningDay: "星期四" }];
const update = api.plan(edited, saved);
assert.equal(update.update, 1);
assert.equal(update.changes[0].id, "place-0", "matching pair preserves id");
const rows = [api.HEADERS, ["  測試泳池  ", " 室內池 ", "  集合位置 ", " 星期二 ", " 11月 "]];
assert.equal(api.normalizeRows(rows)[0].pool, "測試泳池", "sheet values are trimmed");
assert.throws(() => api.normalizeRows([api.HEADERS, rows[1], rows[1]]), /組合重複/);
assert.throws(() => api.normalizeRows([["課堂泳池", "泳池地點", "集合位置", "泳池清潔日", "錯誤欄位"], rows[1]]), /欄位/);
assert.match(api.toCsv(), /課堂泳池/);
assert.throws(() => api.setReferenceRows([{ pool: "壞資料" }]), /格式錯誤/);
console.log("Location import tests passed: protected catalog, CSV, pair keys and update planning.");
